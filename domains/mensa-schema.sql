    FOR EACH ROW EXECUTE FUNCTION set_row_audit();
CREATE TRIGGER set_row_audit BEFORE INSERT OR UPDATE ON meal_profile_diets
    FOR EACH ROW EXECUTE FUNCTION set_row_audit();
