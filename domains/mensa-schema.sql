-- Essensvariante, nach der die Küche kocht und zählt ("Vegetarisch",
-- "Laktosefrei", "Glutenfrei"). Lookup statt dreier Boolean-Spalten (rules.md
-- Abschnitt 3): die Küche gruppiert danach (wie viele vegetarische Portionen
-- heute), und eine weitere Variante („vegan") ist eine Zeile statt einer
-- Migration. Kein code daneben: an keiner Variante hängt Systemverhalten,
-- eine Umbenennung ändert nur den Anzeigetext.
CREATE TABLE meal_diet_types (
    meal_diet_type_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             text NOT NULL UNIQUE CHECK (label <> '')
);

-- ---------------------------------------------------------------------------
-- Küchenprofil
-- ---------------------------------------------------------------------------

-- Höchstens ein Profil je Kind — child_id ist zugleich Primärschlüssel, wie
-- beim Masernnachweis. Keine Zeile heißt: der Küche ist nichts mitzuteilen.
--
-- kitchen_note trägt die „sonstigen Unverträglichkeiten" des Formulars als
-- Handlungsangabe an die Küche („keine Nüsse") — Freitext mit benanntem
-- Abnehmer, keine Diagnose (Kopfkommentar).
--
-- ON DELETE RESTRICT wie bei den Gesundheitstabellen und aus demselben Grund:
-- die Essensvariante lässt Rückschlüsse auf Gesundheit (und beim Vegetarischen
-- ggf. Weltanschauung) zu — eine solche Zeile verschwindet nicht als
-- Nebenwirkung eines anderen Löschbefehls, der Lösch-Job räumt sie
-- ausdrücklich zuerst.
CREATE TABLE meal_profiles (
    child_id     uuid PRIMARY KEY REFERENCES children(child_id) ON DELETE RESTRICT,
    kitchen_note text CHECK (kitchen_note <> ''),
    created_at   timestamptz NOT NULL DEFAULT now(),
    created_by   text NOT NULL,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    updated_by   text NOT NULL
);

-- Varianten je Kind, M:N: „vegetarisch UND glutenfrei" ist der reale Fall, den
-- ein Einzelverweis nicht trüge. Hängt am Profil, nicht direkt am Kind — die
-- Profilzeile ist der eine Anker, den die Küchen-Rolle liest, und ohne sie
-- gäbe es zwei getrennt zu grantende Einstiege.
--
-- MIT Audit-Spalten, obwohl das Profil sie trägt: die Variante IST hier die
-- Aussage — eine entfernte Laktose-Zeile ändert, was ein Kind zu essen
-- bekommt, und die Profilzeile bliebe dabei unberührt. Dieselbe Abwägung wie
-- bei care_module_booking_days.
CREATE TABLE meal_profile_diets (
    child_id          uuid NOT NULL REFERENCES meal_profiles(child_id) ON DELETE CASCADE,
    meal_diet_type_id integer NOT NULL REFERENCES meal_diet_types(meal_diet_type_id) ON DELETE RESTRICT,
    created_at        timestamptz NOT NULL DEFAULT now(),
    created_by        text NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    updated_by        text NOT NULL,
    PRIMARY KEY (child_id, meal_diet_type_id)
);

