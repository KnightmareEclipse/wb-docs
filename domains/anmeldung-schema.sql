-- Kindergarten der abgebenden Seite bei der Grundschul-Voranmeldung. Eigene
-- Liste und NICHT previous_schools: die trägt die staatlichen
-- Überweisungspartner, ein Kindergarten darin verschöbe die Bedeutung einer
-- bestehenden Stammdaten-Spalte (domains/grenzkarte.md).
CREATE TABLE kindergartens (
    kindergarten_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label           text NOT NULL UNIQUE CHECK (label <> '')
);

-- Empfehlung des Kindergartens: Einschulung oder Zurückstellung. Werteliste
-- statt CHECK, wie jede Kategorie in diesem Projekt (rules.md Abschnitt 3) —
-- eine dritte Ausprägung ist damit eine Zeile statt einer Migration.
CREATE TABLE kindergarten_recommendations (
    kindergarten_recommendation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label                          text NOT NULL UNIQUE CHECK (label <> '')
);

-- Schulpflicht-Einstufung des Kindes: schulpflichtig, Kann-Kind, zurückgestellt.
-- Die Einstufung wird gespeichert und nicht bei jeder Anzeige neu gerechnet: sie
-- ist eine Entscheidung, kein Rechenergebnis — ein schulpflichtiges Kind kann
-- zurückgestellt werden (domains/anmeldung.md).
CREATE TABLE enrollment_categories (
    enrollment_category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label                  text NOT NULL UNIQUE CHECK (label <> '')
);

-- Stichtage, aus denen die Oberfläche die Einstufung VORSCHLÄGT. Als Daten und
-- nicht im Code, weil die Schule ausdrücklich sagt, dass sie sich immer mal
-- wieder ändern (rules.md Abschnitt 3, prozesse.md Abschnitt 5.3). Aktuell: wer
-- bis zum 30.06. sechs wird, ist schulpflichtig; ab dem 01.07. Kann-Kind.
-- Je Zielschuljahr eine Zeile — ein geänderter Stichtag gilt nie rückwirkend
-- für ein bereits laufendes Verfahren.
-- school_year überall in diesem Schema mit demselben Formatprüf-CHECK
-- (JJJJ/JJ, z. B. "2027/28"). Nötig, weil das Schuljahr hier ein TRAGENDER
-- Verbindungswert ist und kein Anzeigetext: die Oberfläche findet den Stichtag
-- einer Bewerbung, indem sie applications.target_school_year gegen diese Spalte
-- hält. Ein Fremdschlüssel darauf wäre falsch — eine Bewerbung darf existieren,
-- bevor jemand den Stichtag des Jahrgangs gepflegt hat —, aber ohne
-- Formatprüfung liefen "2027/28", "2027/2028" und "27/28" nebeneinander und der
-- Vergleich fände still nichts: keine Fehlermeldung, nur ein fehlender
-- Vorschlag, und die Einstufung wird ungeprüft von Hand gesetzt. Stammdaten hat
-- für dieselbe Tatsache dieselbe Entscheidung getroffen (classes.entry_year,
-- vierstellig gegen Mehrdeutigkeit).
CREATE TABLE enrollment_cutoffs (
    enrollment_cutoff_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_year          text NOT NULL UNIQUE CHECK (school_year ~ '^[0-9]{4}/[0-9]{2}$'),   -- z. B. "2027/28"
    cutoff_on            date NOT NULL,
    compulsory_age       smallint NOT NULL CHECK (compulsory_age BETWEEN 4 AND 10),
    created_at           timestamptz NOT NULL DEFAULT now(),
    created_by           text NOT NULL,
    updated_at           timestamptz NOT NULL DEFAULT now(),
    updated_by           text NOT NULL
);

-- Anmeldefenster der Voranmeldung je Zweig und Zielschuljahr — das Gegenstück
-- zu cleaning_cycles (Putzdienst) und programs.booking_closes_at (Ferien).
-- Beides sind organisatorische Werte, die sich zyklisch ändern, und gehören
-- deshalb als Daten hierher, nicht in Code oder Deploy-Konfiguration (rules.md
-- Abschnitt 3): die Anmeldung wird real je Schule dynamisch geschlossen —
-- Zeitpunkt hängt an der Bewerberzahl, teils blieb sie bis Juni offen
-- (prozesse.md Abschnitt 3.1) — und je Zweig, weil Grund- und Realschule nicht
-- am selben Tag schließen. Deshalb eine Zeile je Zweig × Schuljahr, nicht je
-- Schuljahr.
--
-- Das Fenster trägt die gewünschte HARTE SPERRE (prozesse.md Abschnitt 3.4):
-- offen/zu ist ein Vergleich des Backends gegen diese Zeile, kein Constraint —
-- der benannte legitime Ausweg ist der einzelne Nachmeldelink des Sekretariats
-- in die reguläre Voranmeldung, ein Vorgang und kein Datenzustand. Der
-- Quereinstieg (applications.is_lateral_entry) läuft ganzjährig am Fenster
-- vorbei; seine Gebühr liest er trotzdem hier, aus der Zeile seines Zieljahrs.
--
-- fee ist die Anmeldegebühr, gezahlt beim Absenden (prozesse.md Abschnitt 3.1);
-- payments.amount bleibt wie beim Putzdienst die Kopie zum Zahlungszeitpunkt.
-- Je Zweig ein eigener Betrag, auch wenn beide heute gleich sein mögen: zwei
-- einzeln gesetzte Entscheidungen, keine Ableitung — dieselbe Abwägung wie
-- buyout_amount/slot_buyout_amount am Putzdienst-Zyklus.
--
-- Kein Fremdschlüssel von applications hierher — eine Bewerbung darf
-- existieren, bevor jemand das Fenster des Jahrgangs gepflegt hat (Nachmeldung,
-- Quereinstieg), dieselbe Entscheidung wie bei enrollment_cutoffs; die
-- Verbindung läuft über (school_branch_id, school_year). Und anders als beim
-- Putzdienst-Buchungsfenster kein Überlappungs-Constraint: die Bewerbung
-- benennt ihr Zieljahr selbst, „wofür wird gerade gebucht" ist hier nie
-- mehrdeutig — zwei gleichzeitig offene Fenster (beide Zweige, zwei Jahrgänge)
-- sind der Normalfall, kein Fehler.
CREATE TABLE application_windows (
    application_window_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_branch_id      integer NOT NULL REFERENCES school_branches(school_branch_id) ON DELETE RESTRICT,
    school_year           text NOT NULL CHECK (school_year ~ '^[0-9]{4}/[0-9]{2}$'),  -- Format begruendet an enrollment_cutoffs
    opens_at              timestamptz NOT NULL,
    closes_at             timestamptz NOT NULL,
    fee                   numeric(8,2) NOT NULL CHECK (fee >= 0),
    created_at            timestamptz NOT NULL DEFAULT now(),
    created_by            text NOT NULL,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    updated_by            text NOT NULL,
    UNIQUE (school_branch_id, school_year),
    CONSTRAINT application_windows_period_check CHECK (closes_at > opens_at)
);

-- Angebote, deren Wahrnehmung bei der Zusage einen Bonus gibt (Musikarche,
-- Ferienprogramm, Clemens-KITA). Selbstauskunft im Formular, deshalb eine
-- Werteliste und kein Verweis auf echte Buchungen: ein Ferienprogramm-Besuch von
-- vor drei Jahren steht in keiner Buchungstabelle, die noch existiert.
CREATE TABLE school_programs (
    school_program_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             text NOT NULL UNIQUE CHECK (label <> '')
);

-- Status der Bewerbung. Trägt den gesamten Lebenslauf und ersetzt drei
-- naheliegende Zusatzentitäten: Warteliste, Absage und der Rücktritt vor dem
-- ersten Schultag sind Ausprägungen dieses Feldes (domains/grenzkarte.md).
--
-- Zwei nicht umbenennbare Kennzeichen daneben, gleiche Bauform wie
-- cleaning_duty_types.is_major: is_waitlist steuert die jährliche
-- Fortschreibung, is_final beendet das Verfahren und startet die Löschfrist.
-- Beide dürfen sich nicht ändern, wenn jemand das Label umbenennt.
CREATE TABLE application_statuses (
    application_status_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label                 text NOT NULL UNIQUE CHECK (label <> ''),
    is_waitlist           boolean NOT NULL DEFAULT false,
    is_final              boolean NOT NULL DEFAULT false,
    created_at            timestamptz NOT NULL DEFAULT now(),
    created_by            text NOT NULL,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    updated_by            text NOT NULL,
    -- Ein Status kann nicht zugleich „wartet" und „ist abgeschlossen" sein.
    CONSTRAINT application_statuses_waitlist_not_final_check
        CHECK (NOT (is_waitlist AND is_final))
);

-- Schulart-Niveau: Hauptschule, Realschule, Gymnasium. EINE Liste für ZWEI
-- Spalten der Bewerbung — die amtliche Grundschulempfehlung und die eigene
-- Einschätzung aus Gespräch und Testblättern (Begründung an applications).
CREATE TABLE school_recommendations (
    school_recommendation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label                    text NOT NULL UNIQUE CHECK (label <> '')
);

-- Konsolidierte Einschätzung „passt zur Schule": Zusage / Eher Ja / Eher Nein /
-- Absage. sort_order, weil die Reihenfolge fachlich ist und nicht alphabetisch.
CREATE TABLE fit_assessments (
    fit_assessment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             text NOT NULL UNIQUE CHECK (label <> ''),
    sort_order        smallint NOT NULL UNIQUE
);

