-- Q3 — Zahlungsvorgang erweitern
-- ---------------------------------------------------------------------------

-- Die Anmeldegebühr ist der dritte Stripe-Anlass (domains/grenzkarte.md, Q3).
-- Sie kommt als weitere nullable Vorgangs-Spalte samt erweitertem
-- Entweder-oder-CHECK an die bestehende Tabelle — nicht als zweite
-- Zahlungstabelle: der Fremdschlüssel trägt die Unterscheidung, und genau die
-- referenzielle Integrität ist der Grund, Q3 überhaupt einmal zu bauen.
-- ON DELETE RESTRICT wie bei den beiden Putzdienst-Anlässen: die Zahlungszeile
-- geht mit ihrer Bewerbung, aber nicht nebenbei. Sie bleibt auch nicht als
-- vorgangsloser Beleg stehen — Optigem ist für die Buchhaltung führend und zieht
-- die Zahlung selbst aus Stripe (fachdomaenen.md Abschnitt 4), Weltenbaum
-- braucht sie nach dem Verfahren also nicht mehr. Damit bleibt der
-- Entweder-oder-CHECK unangetastet: eine Zahlung ohne Anlass gibt es nie, und
-- eine leere Vorgangsspalte ist immer ein Fehler und nie ein Zustand.
--
-- Folge für den Lösch-Job: er räumt von außen nach innen — Zahlung, dann
-- Zustimmung, Signatur und Dokument samt SharePoint-Datei (in dieser
-- Reihenfolge: consents.signature_id blockiert die Signatur,
-- signatures.document_id das Dokument), dann der Vertragsvorgang, dann die
-- Bewerbung (domains/anmeldung.md, „Löschung"). Die Fremdschlüssel erzwingen
-- die Reihenfolge, statt sie ihm zu überlassen — wer eine Stufe überspringt,
-- bricht mit einer Fremdschlüssel-Verletzung ab und hinterlässt einen halb
-- geräumten Bestand.
ALTER TABLE payments
    ADD COLUMN application_id uuid UNIQUE REFERENCES applications(application_id) ON DELETE RESTRICT;

ALTER TABLE payments DROP CONSTRAINT payments_exactly_one_subject_check;
ALTER TABLE payments ADD CONSTRAINT payments_exactly_one_subject_check
    CHECK ((cleaning_buyout_id IS NOT NULL)::int
         + (cleaning_slot_buyout_id IS NOT NULL)::int
         + (application_id IS NOT NULL)::int = 1);

-- ---------------------------------------------------------------------------
-- Q5 — Nachzieh-Aufgabe
-- ---------------------------------------------------------------------------

-- ASV-BW und Optigem haben keine Update-Schnittstelle: jede Änderung, die in
-- Weltenbaum passiert, muss ein Mensch dort nachziehen — heute über Zuruf und
-- Gedächtnis, ohne dass ein Ausbleiben auffiele (prozesse.md Abschnitt 2). Q5
-- macht daraus eine benannte Aufgabe mit Erledigt-Zustand
-- (domains/grenzkarte.md, Q5). Hier gebaut, weil der erste reale Abnehmer die
-- Neuanlage in ASV-BW nach Vertragsabschluss ist (prozesse.md Abschnitt 7.1,
-- Schritt 8); die alltägliche Datenänderung der Stammdaten erzeugt später
-- dieselben Aufgaben.
--
-- Gespeichert wird nur, was sich nicht ableiten lässt: WAS zu tun ist und OB
-- es erledigt wurde. Die Änderung selbst steht in den Audit-Spalten der
-- geänderten Zeile, und welches Feld welches Fremdsystem betrifft, ist eine
-- statische Abbildung im Code, der die Aufgabe erzeugt — beides bekommt
-- deshalb keine Tabelle (domains/grenzkarte.md, Q5). Die Erzeugung und
-- Abarbeitung der Aufgaben ist Backend-Arbeit in wb-backend und ausdrücklich
-- NICHT Teil dieses Entwurfs — hier steht nur die Struktur.

-- Fremdsystem, in das nachzuziehen ist ("ASV-BW", "Optigem", "Microsoft 365").
-- code als stabiler Anker wie an consent_purposes und aus demselben Grund: der
-- Code, der Aufgaben erzeugt, wählt das Zielsystem programmatisch — auf dem
-- frei umbenennbaren label aufgesetzt bräche das still.
CREATE TABLE sync_targets (
    sync_target_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label          text NOT NULL UNIQUE CHECK (label <> ''),
    code           text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{0,31}$')  -- z. B. "asv_bw", "optigem", "m365"
);

-- Eine offene oder erledigte Nachzieh-Aufgabe. completed_at NULL heißt offen;
-- WER erledigt hat, trägt die ohnehin vorhandene updated_by-Spalte — dieselbe
-- Bauform wie cleaning_assignments.penalty_waived_at.
--
-- person_id sagt, WEN die Aufgabe betrifft, und ist bewusst ON DELETE CASCADE:
-- eine Aufgabe ist operativ, nichts Vereinbartes — löscht der Lösch-Job Jahre
-- später die Person, ist nichts mehr nachzuziehen, und eine stehengebliebene
-- Aufgabenzeile wäre selbst ein Personenbezug ohne Zweck. Damit die Kaskade
-- sauber bleibt, beschreibt description die AUFGABE („Adresse in Optigem
-- aktualisieren"), nie die Person — Name und Kontext folgen aus person_id.
-- Nullable für personenlose Aufgaben (z. B. ein Klassenverteiler in M365).
-- description ist Freitext mit benanntem Abnehmer: die Aufgabenliste, die das
-- Sekretariat abarbeitet — vom erzeugenden Code formuliert, nicht von Hand.
CREATE TABLE sync_tasks (
    sync_task_id   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    sync_target_id integer NOT NULL REFERENCES sync_targets(sync_target_id) ON DELETE RESTRICT,
    person_id      uuid REFERENCES persons(person_id) ON DELETE CASCADE,
    description    text NOT NULL CHECK (description <> ''),
    completed_at   timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    created_by     text NOT NULL,
    updated_at     timestamptz NOT NULL DEFAULT now(),
    updated_by     text NOT NULL
);
CREATE INDEX ON sync_tasks (person_id);
-- Die Arbeitsliste des Sekretariats: alle offenen Aufgaben je Zielsystem.
CREATE INDEX sync_tasks_open_by_target ON sync_tasks (sync_target_id) WHERE completed_at IS NULL;

