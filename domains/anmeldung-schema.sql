-- ---------------------------------------------------------------------------
-- Schulvertrag
-- ---------------------------------------------------------------------------

-- Der Vertragsvorgang beginnt mit der Zusage und endet mit der Bestätigungsmail.
-- 1:1 zur Bewerbung (UNIQUE), aber eigene Zeile und keine Spalten an der
-- Bewerbung: er hat einen eigenen Lebenslauf mit vier Stationen, von denen drei
-- nach dem Absenden der Eltern liegen, und die meisten Bewerbungen erreichen ihn
-- nie.
--
-- Die vier Zeitpunkte sind bewusst Zeitpunkte und kein Statusfeld: sie treten
-- immer in dieser Reihenfolge ein, und „wann war das" ist die Frage, die im
-- Nachhinein gestellt wird (domains/anmeldung.md).
CREATE TABLE contracts (
    contract_id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    application_id        uuid NOT NULL UNIQUE REFERENCES applications(application_id) ON DELETE RESTRICT,
    -- Frist für die Eltern, real 14 Tage ab Versand. Als Datum und nicht als
    -- Dauer, weil das Sekretariat sie im Einzelfall verlängert.
    deadline_on           date NOT NULL,
    secretariat_checked_at timestamptz,
    headmaster_released_at timestamptz,
    confirmation_sent_at   timestamptz,
    created_at            timestamptz NOT NULL DEFAULT now(),
    created_by            text NOT NULL,
    updated_at            timestamptz NOT NULL DEFAULT now(),
    updated_by            text NOT NULL,
    -- Die Reihenfolge ist Teil des Verfahrens: erst prüft das Sekretariat, dann
    -- gibt die Schulleitung frei, dann geht die Bestätigung raus. Eine
    -- Bestätigungsmail vor der Freigabe wäre genau der Fehler, der an dieser
    -- Schule niemandem auffiele.
    CONSTRAINT contracts_release_after_check_check
        CHECK (headmaster_released_at IS NULL OR secretariat_checked_at IS NOT NULL),
    CONSTRAINT contracts_confirmation_after_release_check
        CHECK (confirmation_sent_at IS NULL OR headmaster_released_at IS NOT NULL)
);

-- Antwort je Erziehungsberechtigtem. Eigene Zeilen und kein Feld am Vertrag,
-- weil Mutter und Vater je einen eigenen persönlichen Link bekommen und
-- UNTERSCHIEDLICH antworten können — sagt einer ja und der andere nein, wird das
-- Sekretariat benachrichtigt und klärt telefonisch (prozesse.md Abschnitt 7.1).
-- Genau dieser Konflikt ist an einem einzelnen Vertragsfeld nicht darstellbar.
--
-- Die Stammdatenbestätigung steht daneben: jeder bestätigt seine EIGENEN Daten,
-- die des Kindes bestätigen beide — deshalb zwei Zeitpunkte je Zeile und nicht
-- einer.
CREATE TABLE contract_responses (
    contract_id             uuid NOT NULL REFERENCES contracts(contract_id) ON DELETE CASCADE,
    person_id               uuid NOT NULL REFERENCES persons(person_id) ON DELETE RESTRICT,
    accepted                boolean,
    responded_at            timestamptz,
    own_data_confirmed_at   timestamptz,
    child_data_confirmed_at timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    created_by              text NOT NULL,
    updated_at              timestamptz NOT NULL DEFAULT now(),
    updated_by              text NOT NULL,
    PRIMARY KEY (contract_id, person_id),
    -- Eine Antwort ohne Zeitpunkt ist keine, und ein Zeitpunkt ohne Antwort
    -- ebenso wenig.
    CONSTRAINT contract_responses_answer_complete_check
        CHECK ((accepted IS NULL) = (responded_at IS NULL))
);
CREATE INDEX ON contract_responses (person_id);

-- ---------------------------------------------------------------------------
-- Betreuungsmodule (Hortvertrag)
-- ---------------------------------------------------------------------------

-- Katalog der buchbaren Module: Frühbetreuung, vier Nachmittagsvarianten, Hort
-- nach Mittagschule (prozesse.md Abschnitt 8). Werteliste, weil die Schule
-- Module streicht und ergänzt, ohne dass eine Migration nötig sein darf.
--
-- school_branch_id nullable: „Hort nach Mittagschule" gilt nur für die
-- Realschule, alle übrigen für beide Zweige. NULL heißt also „ohne
-- Einschränkung" und nicht „unbekannt".
CREATE TABLE care_modules (
    care_module_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             text NOT NULL UNIQUE CHECK (label <> ''),
    school_branch_id  integer REFERENCES school_branches(school_branch_id) ON DELETE RESTRICT,
    -- Zeiten als Text und nicht als time-Spalten: der reale Katalog beginnt
    -- überwiegend bei „Schulende" und nicht zu einer Uhrzeit, und diese Angabe
    -- steht im Formular, wird aber von keiner Abfrage ausgewertet.
    time_description  text NOT NULL CHECK (time_description <> ''),
    includes_homework boolean NOT NULL DEFAULT false,
    sort_order        smallint NOT NULL UNIQUE,
    created_at        timestamptz NOT NULL DEFAULT now(),
    created_by        text NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    updated_by        text NOT NULL
);

-- Gebuchtes Modul für ein Kind, mit eigenem Gültigkeitszeitraum.
--
-- Hängt am KIND und nicht am Vertragsvorgang: der Hort nimmt auch Kinder auf,
-- die weder Grund- noch Realschüler sind (prozesse.md Abschnitt 8) — für sie
-- gibt es keine Bewerbung, aber eine Buchung. contract_id bleibt deshalb
-- nullable und sagt nur, aus welchem Anmeldevorgang die Buchung entstanden ist.
--
-- valid_until trägt die automatische Kündigung: bis Ende Klasse 4, ein Vertrag
-- für Klasse 5 gilt nur für Klasse 5, mit Klasse 5 endet das Angebot. Als Datum
-- und nicht als Regel im Code, weil die Schule die Grenzen verschiebt.
CREATE TABLE care_module_bookings (
    care_module_booking_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    child_id               uuid NOT NULL REFERENCES children(child_id) ON DELETE RESTRICT,
    care_module_id         integer NOT NULL REFERENCES care_modules(care_module_id) ON DELETE RESTRICT,
    contract_id            uuid REFERENCES contracts(contract_id) ON DELETE RESTRICT,
    valid_from             date NOT NULL,
    valid_until            date,
    created_at             timestamptz NOT NULL DEFAULT now(),
    created_by             text NOT NULL,
    updated_at             timestamptz NOT NULL DEFAULT now(),
    updated_by             text NOT NULL,
    UNIQUE (child_id, care_module_id, valid_from),
    CONSTRAINT care_module_bookings_period_check
        CHECK (valid_until IS NULL OR valid_until >= valid_from)
);
CREATE INDEX ON care_module_bookings (child_id);

-- Die Buchungseinheit ist Modul × Wochentag, nicht das Modul allein: je Modul
-- werden die einzelnen Tage gewählt (prozesse.md Abschnitt 8). Deshalb eine
-- eigene Zeile je Tag und keine sieben Boolean-Spalten — ein Wochentag mehr oder
-- weniger ist damit ein Datensatz.
CREATE TABLE care_module_booking_days (
    care_module_booking_id uuid NOT NULL REFERENCES care_module_bookings(care_module_booking_id) ON DELETE CASCADE,
    -- ISO-8601: 1 = Montag … 5 = Freitag. Betreuung am Wochenende gibt es nicht,
    -- und ein Tippfehler „7" wäre sonst eine stille Buchung ins Leere.
    weekday                smallint NOT NULL CHECK (weekday BETWEEN 1 AND 5),
    PRIMARY KEY (care_module_booking_id, weekday)
);

