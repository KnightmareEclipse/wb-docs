-- Anmelde-Schema: Voranmeldung, Anmeldegespräch und Schulvertrag (Domäne 2/4,
-- fachdomaenen.md Abschnitt 6) samt den Querschnitts-Entitäten Zustimmung (Q1)
-- und Dokument/Signatur (Q2) und der Erweiterung des Zahlungsvorgangs (Q3).
-- Konzeptioneller Entwurf zu domains/anmeldung.md und domains/grenzkarte.md —
-- konkreter als Prosa, aber noch kein Alembic-Migrationscode.
--
-- SETZT domains/stammdaten-schema.sql UND domains/putzdienst-schema.sql VORAUS
-- und wird nach beiden geladen: es referenziert children/persons/grade_levels
-- und erweitert die dort gebaute payments-Tabelle. Es nutzt außerdem
-- set_row_audit() samt app.actor-Präfixregel aus Stammdaten; eine zweite
-- Audit-Variante gibt es bewusst nicht.
--
-- Stammdaten sind ab dem Vollimport eingefroren (domains/grenzkarte.md, „Freeze
-- der Stammdaten"). Dieses Schema hält sich daran: es legt in Stammdaten Zeilen
-- an und ändert sie (das ist sein Zweck, fachdomaenen.md Abschnitt 6), aber es
-- ändert dort keine einzige Spalte, keinen Typ und keinen Constraint.
--
-- id-Typ wie in den beiden anderen Schemata: uuid, wo eine Zeile in einer
-- Eltern-URL auftauchen kann (Bewerbung, Vertragsvorgang, Zustimmung, Dokument,
-- Signatur, Betreuungsbuchung), integer-Identity für die rein intern gepflegten
-- Verwaltungs- und Wertelisten.
--
-- ZWEI STRUKTURENTSCHEIDUNGEN, aus denen der Rest folgt:
--
--   1. Die Personenzeilen entstehen bei der VORANMELDUNG, nicht erst bei der
--      Aufnahme. Drei Gründe, von denen jeder allein trägt: Personendaten haben
--      genau ein Zuhause und werden nie kopiert (domains/grenzkarte.md, Regel 2)
--      — eine Bewerbung mit eigenen Namens-, Geburts- und Adressfeldern wäre
--      genau diese Kopie; der OTP-Zugang, die jährliche Wartelisten-Rückfrage
--      und die persönlichen Vertragslinks brauchen alle eine Personenidentität,
--      und die Warteliste läuft über Jahre; und die Dublettenvermeidung ist eine
--      Auswahl aus bekannten Personen, kein Abgleich (TODO-SESSIONS.md).
--      Preis: Bewerbungen, die nie zur Aufnahme führen, hinterlassen
--      Personenzeilen. Sie sind daran erkennbar, dass children.entry_date leer
--      ist und alle Bewerbungen des Kindes in einem Endstatus stehen — eine
--      Abfrage des Lösch-Jobs, keine Spalte (idea/06-dsgvo-organisatorisch.md).
--
--   2. Die Zeilen entstehen beim ABSENDEN, nicht erst nach der
--      Zahlungsbestätigung. Die Alternative hieße, den Formularinhalt bis zur
--      Bestätigung zwischenzuparken — also dieselben Personendaten an einem
--      zweiten Ort mit eigener Aufbewahrung und eigenem Leserkreis. Ein
--      abgebrochener Zahlungsvorgang hinterlässt stattdessen eine Bewerbung mit
--      offener Zahlung, die derselbe Lösch-Job aufräumt.
--
-- Was hier bewusst NICHT steht:
--   * Keine Personenfelder an der Bewerbung (Begründung oben).
--   * Keine Wartelisten-Entität und kein Rangfeld darin. Die Warteliste ist ein
--     Status samt jährlich fortgeschriebener Zielklassenstufe; bei einem frei
--     werdenden Platz entscheidet ein Mensch neu (domains/grenzkarte.md).
--   * Keine Bewertungszeile je Lehrkraft. Festgehalten wird das konsolidierte
--     Ergebnis — mehrere konkurrierende Urteile ohne definierten Sieger gibt es
--     im realen Verfahren nicht (domains/grenzkarte.md, „Bewertung").
--   * Keine Geschwister-Namensliste. Gebraucht werden nur zwei Tatsachen: ob
--     Geschwister an der Schule sind und wie viele es insgesamt sind.
--   * Kein Gesundheitsmerkmal. Der Schulvertrag erhebt den Satz, geführt wird er
--     aber in Domäne 9 mit eigenem Zugriffsprofil; hier steht nur die
--     Zustimmung (Q1) und das signierte Blatt (Q2).
--   * Kein Kindergarten in previous_schools. Der trägt die staatlichen
--     Überweisungspartner; der Kindergarten bekommt seine eigene Werteliste
--     (domains/grenzkarte.md, „Zwei Schulen, nicht eine").
--   * Keine Frist-Prüfung als Constraint. Die 14-Tage-Frist des Vertrags und die
--     Fälligkeiten der Buchung sind Ablauflogik, kein Datenzustand — ebenso die
--     harte Sperre der Voranmeldung: offen/zu ist ein Backend-Vergleich gegen
--     application_windows, kein Constraint.

