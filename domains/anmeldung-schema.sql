-- Ein Anmeldetag je Schulzweig: das Raster, aus dem die Slots entstehen.
-- Wochentag, Zeitfenster, Mittagspause und Kinder je Stunde sind DATEN und
-- keine Konstanten — die zuständigen Personen setzen sie selbst, weil sie sich
-- immer wieder ändern und die Sondertermine heute ohnehin niemand vollständig
-- kennt (prozesse.md Abschnitt 5.1). Der heutige Stand ist damit ein
-- Ausgangswert und keine Regel im Code.
CREATE TABLE interview_days (
    interview_day_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_branch_id integer NOT NULL REFERENCES school_branches(school_branch_id) ON DELETE RESTRICT,
    school_year      text NOT NULL CHECK (school_year ~ '^[0-9]{4}/[0-9]{2}$'),  -- Format begruendet an enrollment_cutoffs
    day_on           date NOT NULL,
    starts_at        time NOT NULL,
    ends_at          time NOT NULL,
    break_starts_at  time,
    break_ends_at    time,
    created_at       timestamptz NOT NULL DEFAULT now(),
    created_by       text NOT NULL,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    updated_by       text NOT NULL,
    UNIQUE (school_branch_id, day_on),
    -- Ziel des zusammengesetzten Fremdschlüssels von interview_slots — hält
    -- deren school_branch_id konsistent zum Tag, an dem sie hängen. Gleiche
    -- Bauform wie grade_levels.UNIQUE (grade_level_id, school_branch_id) in
    -- Stammdaten.
    UNIQUE (interview_day_id, school_branch_id),
    CONSTRAINT interview_days_period_check CHECK (ends_at > starts_at),
    -- Pause gilt nur ganz oder gar nicht, und sie liegt innerhalb des Tages.
    CONSTRAINT interview_days_break_complete_check
        CHECK ((break_starts_at IS NULL) = (break_ends_at IS NULL)),
    CONSTRAINT interview_days_break_within_day_check
        CHECK (break_starts_at IS NULL
               OR (break_ends_at > break_starts_at
                   AND break_starts_at >= starts_at AND break_ends_at <= ends_at))
);

-- Konkreter buchbarer Slot. Eigene Zeilen statt einer Berechnung aus dem Raster:
-- eine Buchung braucht ein stabiles Ziel, das auch dann noch dasselbe meint,
-- wenn jemand die Pause des Tages verschiebt.
--
-- Kapazität am Slot, weil real 4–5 Kinder je Stunde verarbeitet werden und die
-- Zahl je Tag schwankt. Sie ist hier eine harte Obergrenze für die
-- Selbstbuchung durch die Eltern — anders als beim Putzdienst, wo die Kapazität
-- berechnet wird und das Sekretariat sie überschreiten darf.
--
-- Hart heißt nicht schemaseitig: eine Obergrenze über die Summe der Buchungen
-- eines Slots ist eine Bedingung über mehrere Zeilen und damit kein CHECK. Sie
-- gehört in die Backend-Stelle, die den Termin vergibt, und zwar in derselben
-- Transaktion mit einer Sperre auf dieser Slot-Zeile — sonst prüfen zwei
-- gleichzeitige Elternbuchungen beide gegen denselben Stand und der letzte
-- Platz wird zweimal vergeben. Gleiche Bringschuld wie bei
-- program_days.capacity (domains/ferien-schema.sql).
-- school_branch_id ist eine kontrollierte Doppelung zum Anmeldetag, keine zweite
-- Pflegestelle: sie trägt allein den zusammengesetzten Fremdschlüssel von
-- applications unten, der verhindert, dass eine Grundschul-Bewerbung in einen
-- Realschul-Slot gebucht wird. Über den Ableitungsweg (Slot → Tag → Zweig) lässt
-- sich das nicht ausdrücken, und genau dafür erlaubt rules.md Abschnitt 1 die
-- Ausnahme — gebunden an ihr Original durch den zusammengesetzten
-- Fremdschlüssel, damit beide gar nicht erst auseinanderlaufen können.
-- Dasselbe Muster wie classes.school_branch_id in Stammdaten.
CREATE TABLE interview_slots (
    interview_slot_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_day_id  integer NOT NULL,
    school_branch_id  integer NOT NULL,
    starts_at         time NOT NULL,
    capacity          smallint NOT NULL CHECK (capacity > 0),
    created_at        timestamptz NOT NULL DEFAULT now(),
    created_by        text NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    updated_by        text NOT NULL,
    UNIQUE (interview_day_id, starts_at),
    -- Ziel des zusammengesetzten Fremdschlüssels von applications.
    UNIQUE (interview_slot_id, school_branch_id),
    -- Kein zusätzlicher einspaltiger Fremdschlüssel auf interview_days daneben:
    -- dieser verlangt ohnehin eine Zeile mit passendem (id, school_branch_id),
    -- beide Spalten sind NOT NULL, und beim Löschen eines Tages blockiert er
    -- genauso. Gleiche Abwägung wie an classes.grade_level_id in Stammdaten.
    FOREIGN KEY (interview_day_id, school_branch_id)
        REFERENCES interview_days(interview_day_id, school_branch_id)
);

