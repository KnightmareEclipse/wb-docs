-- Die Bewerbung ZEIGT auf Kind und Familie, statt Personendaten zu kopieren
-- (Kopfkommentar, Entscheidung 1). Sie trägt nur, was die Bewerbung selbst
-- betrifft.
--
-- Mehrere Bewerbungen je Kind sind der Normalfall, nicht der Ausnahmefall: der
-- Wechsel von der eigenen Grundschule in die eigene Realschule ist eine zweite
-- Bewerbung desselben Kindes, und eine abgelehnte Bewerbung kann im Folgejahr
-- wiederholt werden. Deshalb UNIQUE nur je Kind und Zielschuljahr.
--
-- Ein NEUER Anlauf im SELBEN Zieljahr (Absage im Frühjahr, Quereinstiegsversuch
-- vor dem 01.08.) ist dagegen bewusst keine zweite Zeile: das Sekretariat
-- öffnet die bestehende per Status wieder — der benannte Ausweg. Eine zweite
-- Anmeldegebühr entsteht dabei nicht (payments.application_id ist UNIQUE), und
-- nach dem Lösch-Lauf zum 01.08. (domains/anmeldung.md, „Löschung") ist die
-- Zeile für einen späten Quereinstieg ohnehin frei.
--
-- registration_date steht daneben an children und ist keine Doppelung: das
-- Anmeldedatum überlebt die Bewerbung, die eine kürzere Löschfrist hat
-- (domains/stammdaten.md, „Felder").
CREATE TABLE applications (
    application_id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    child_id                   uuid NOT NULL REFERENCES children(child_id) ON DELETE RESTRICT,
    application_status_id      integer NOT NULL REFERENCES application_statuses(application_status_id) ON DELETE RESTRICT,
    -- Ziel der Bewerbung. Die Klassenstufe wird bei Wartelistenfällen jährlich
    -- fortgeschrieben (Klasse 5 → Klasse 6), das Zielschuljahr ebenso — deshalb
    -- zwei Spalten und keine Ableitung aus dem Anmeldedatum.
    target_school_year         text NOT NULL CHECK (target_school_year ~ '^[0-9]{4}/[0-9]{2}$'),  -- Format begruendet an enrollment_cutoffs
    target_grade_level_id      integer NOT NULL,
    -- Zweig der Zielklassenstufe, kontrollierte Doppelung wie bei
    -- interview_slots und aus demselben Grund: nur mit einer echten Spalte lässt
    -- sich schemaseitig erzwingen, dass der gebuchte Gesprächsslot zum Zweig der
    -- Bewerbung gehört (beide Fremdschlüssel unten). Ohne sie ließe sich eine
    -- Grundschul-Bewerbung in einen Realschul-Anmeldetag buchen — auffallen
    -- würde es erst an der Gesprächsliste, wenn der Termin schon vergeben ist.
    -- Sie ist außerdem für sich brauchbar („alle Realschul-Bewerbungen dieses
    -- Jahrgangs") und spart dort den Join über grade_levels.
    school_branch_id           integer NOT NULL,
    -- Quereinstieg ist ein eigener Ablauf (ganzjährig, Platzprüfung vor dem
    -- Gespräch) und kein Nebeneffekt der Zielklassenstufe: ableitbar wäre er nur
    -- über ein Kennzeichen „Eingangsklassenstufe" an grade_levels, das es dort
    -- nicht gibt und für das eine eingefrorene Stammdaten-Tabelle nicht
    -- aufgemacht wird.
    is_lateral_entry           boolean NOT NULL DEFAULT false,
    -- Hospitationszeitraum des Quereinstiegs (Quereinsteiger-Checkliste,
    -- domains/grenzkarte.md, „Bewerbung"). Bewusst KEIN CHECK gegen
    -- is_lateral_entry: eine Hospitation außerhalb des Quereinstiegs zu
    -- verbieten wäre eine Sperre ohne benannten Bedarf — dieselbe Abwägung wie
    -- bei zwei regulären Putzterminen am selben Tag (cleaning_slots).
    trial_attendance_starts_on date,
    trial_attendance_ends_on   date,
    submitted_on               date NOT NULL DEFAULT current_date,
    -- Wer das Formular ausgefüllt hat und die Bestätigung, dass der andere
    -- Elternteil informiert ist — beides steht so auf dem realen Formular.
    filled_by_person_id        uuid REFERENCES persons(person_id) ON DELETE RESTRICT,
    other_parent_informed      boolean NOT NULL DEFAULT false,
    attended_info_evening      boolean NOT NULL DEFAULT false,
    -- Geschwister als Selbstauskunft, weil es bei externen Bewerbern noch keine
    -- Familie gibt, aus der es folgen könnte. Bei der Aufnahme löst es sich
    -- gegen families auf. Bewusst ohne Namensliste (Kopfkommentar).
    siblings_at_school         boolean NOT NULL DEFAULT false,
    sibling_count              smallint CHECK (sibling_count >= 0),
    interested_in_care         boolean NOT NULL DEFAULT false,
    -- Grundschulseite: Kindergarten samt Rücksprache-Erlaubnis und Empfehlung.
    -- Die Erlaubnis ist wie children.previous_school_consent_at ein einmaliges,
    -- sofort verbrauchtes Einverständnis (also NICHT Q1), steht aber an der
    -- Bewerbung und nicht am Kind: die abgebende Schule wird über den
    -- Anmeldetag hinaus gebraucht, der Kindergarten nicht.
    kindergarten_id            integer REFERENCES kindergartens(kindergarten_id) ON DELETE RESTRICT,
    kindergarten_consent_at    timestamptz,
    kindergarten_recommendation_id integer REFERENCES kindergarten_recommendations(kindergarten_recommendation_id) ON DELETE RESTRICT,
    enrollment_category_id     integer REFERENCES enrollment_categories(enrollment_category_id) ON DELETE RESTRICT,
    -- Realschulseite: die amtliche Grundschulempfehlung der abgebenden Schule.
    -- ZWEI Felder mit derselben Werteliste, solange nicht bestätigt ist, dass es
    -- dasselbe ist (domains/grenzkarte.md, „Bewertung"): dies ist das Dokument
    -- der abgebenden Schule, own_recommendation_id unten die eigene Einschätzung
    -- aus Gespräch und Testblättern. Sind es zwei Namen für dieselbe Angabe,
    -- bleibt eine Spalte leer — der billigere Irrtum, denn ein Feld für zwei
    -- Sachverhalte verlöre gerade den interessanten Fall, dass beide
    -- auseinandergehen.
    primary_school_recommendation_id integer REFERENCES school_recommendations(school_recommendation_id) ON DELETE RESTRICT,
    -- Austausch der Schülerüberweisung mit der staatlichen Schule
    -- (children.previous_school_id). DREI Schritte, weil der reale Ablauf drei
    -- hat: wir informieren die abgebende Schule, daraufhin kommt die
    -- Überweisung, und ggf. geht sie zurück. Auf den Checklisten stehen sie
    -- ebenso als drei eigene Punkte („Bisherige örtl. Schule informieren",
    -- „Schülerüberweisung erhalten?", „Rücksendung an Herkunftsschule").
    --
    -- Der erste Schritt braucht eine eigene Spalte, weil er sonst nicht vom
    -- Warten zu unterscheiden wäre: ohne ihn hieße ein leeres
    -- student_transfer_received_on zugleich „wir haben die Schule noch nicht
    -- informiert" (zu tun: informieren) und „die Schule hat noch nicht
    -- geantwortet" (zu tun: nachfassen) — zwei verschiedene Handlungen für
    -- dasselbe Bild. Ein Anker daneben, an dem sich das ablesen ließe, gibt es
    -- hier nicht: der Austausch läuft Wochen nach dem Anmeldetag und damit lange
    -- nach documents_checked_at (domains/grenzkarte.md, „Drei Zustände").
    --
    -- Ein Vorgangsschritt der Bewerbung und bewusst KEINE Q5-Nachzieh-Aufgabe —
    -- er zieht keine Weltenbaum-Änderung in ein Fremdsystem nach, und an zwei
    -- Orten geführt wäre derselbe Erledigt-Haken zweimal pflegbar
    -- (domains/grenzkarte.md, Q5).
    --
    -- Weiterhin kein Reihenfolge-CHECK, und mit dem dritten Schritt erst recht
    -- nicht: die abgebende Schule kann die Überweisung auch unaufgefordert
    -- schicken (die Eltern melden das Kind dort selbst ab), und die Rücksendung
    -- ist ausdrücklich nur „ggf.". Erzwungen wäre das eine Sperre gegen einen
    -- realen Ablauf.
    student_transfer_requested_on date,   -- „Bisherige örtl. Schule informieren"
    student_transfer_received_on  date,
    student_transfer_returned_on  date,
    -- Vollständigkeitsprüfung der Unterlagen am Anmeldetag — der letzte Punkt
    -- der Sekretariats-Checkliste (prozesse.md Abschnitt 5.2) und die
    -- verwaltende der beiden Spuren des Tages. Nicht zu verwechseln mit
    -- contracts.completeness_checked_at: das ist dieselbe Handlung Wochen später
    -- am fertigen Vertrag, hier geht es um die Unterlagen, die die Eltern zum
    -- Gespräch mitbringen (Geburtsurkunde, Zeugnis, Beobachtungsbogen). Welche
    -- davon fehlen, sagt documents.requested_on; DASS jemand durchgesehen hat,
    -- sagt nur diese Spalte — sonst wäre eine vergessene Prüfung von einer
    -- vollständigen Mappe nicht zu unterscheiden.
    documents_checked_at       timestamptz,
    -- Warteliste: die jährliche Rückfrage, ob das Interesse weiterbesteht
    -- (prozesse.md Abschnitt 6). Zwei Spalten, weil die fehlende Antwort selbst
    -- eine Information ist: ohne den Zeitpunkt der Frage wäre „gefragt, keine
    -- Antwort" von „dieses Jahr nie gefragt" nicht zu unterscheiden — über
    -- mehrere Jahre hinweg genau der Fall, in dem eine Familie still liegen
    -- bleibt. Beide werden bei der jährlichen Fortschreibung geleert
    -- (domains/anmeldung.md), sie gelten also immer für das aktuelle
    -- target_school_year. Keine Historie, wie überall.
    waitlist_interest_asked_at     timestamptz,
    waitlist_interest_confirmed_at timestamptz,
    -- Gesprächstermin. Nullable: die Voranmeldung läuft Monate vor der
    -- Terminvergabe. Fremdschlüssel steht unten als zusammengesetzter, der
    -- zugleich den Zweig prüft — ein einspaltiger daneben wäre eine
    -- Einschränkung ohne eigene Wirkung.
    interview_slot_id          integer,
    -- --- Bewertung: engstes Zugriffsprofil im System nach den Art.-9-Daten -----
    -- Vier Spalten, kein eigenes Zugriffssystem: sie bekommen ein eigenes
    -- Spalten-GRANT auf dieser Tabelle (wie die Konfessionsspalten an children),
    -- und sie sind standardmäßig NICHT breit sichtbar. Die Lehrer-Checkliste
    -- bleibt Papier und wird nach dem Verfahren vernichtet; hier landet nur das
    -- konsolidierte Ergebnis samt weniger Notizen (prozesse.md Abschnitt 5.2).
    fit_assessment_id          integer REFERENCES fit_assessments(fit_assessment_id) ON DELETE RESTRICT,
    own_recommendation_id      integer REFERENCES school_recommendations(school_recommendation_id) ON DELETE RESTRICT,
    -- Rangnummer nur für die Grenzfälle der Entscheidungsrunde; klare Zusagen
    -- und klare Absagen brauchen keine. Nach der Entscheidung liest sie niemand
    -- mehr — sie bleibt als Beleg, wie entschieden wurde.
    rank_number                smallint CHECK (rank_number > 0),
    assessment_notes           text CHECK (assessment_notes <> ''),
    -- --- Ende Bewertung -------------------------------------------------------
    -- EIN Freitextfeld für den Bearbeitungsstand, bewusst nicht zwei: die
    -- Trennung zwischen „Bemerkung" und „Stand" wird im Alltag nicht eingehalten
    -- (domains/grenzkarte.md). Kein Notiz-Verlauf, solange niemand danach sucht.
    -- Es nimmt ZWEI Herkünfte auf: den Bearbeitungsstand der Wartelisten-Tabelle
    -- und den „Freitext für zusätzliche Anmerkungen" der Sekretariats-Checkliste
    -- am Anmeldetag (prozesse.md Abschnitt 5.2). Beide gehören der verwaltenden
    -- Spur und damit hierher — NICHT nach assessment_notes: das liegt im
    -- Bewertungsblock unten mit eigenem, engem Spalten-GRANT und ist
    -- standardmäßig nicht breit sichtbar. Eine Anmeldetags-Anmerkung dort wäre
    -- für genau die Verwaltung unlesbar, die sie geschrieben hat.
    processing_note            text CHECK (processing_note <> ''),
    -- Zusammensetzungswunsch für die Klassenbildung — real drei Kinder je
    -- Jahrgang. Eine Kind-zu-Kind-Verknüpfung mit Richtung und Gegenseitigkeit
    -- dafür zu bauen wäre ein Mechanismus ohne Bedarf (domains/grenzkarte.md,
    -- „Klassenbildung").
    class_placement_wish       text CHECK (class_placement_wish <> ''),
    created_at                 timestamptz NOT NULL DEFAULT now(),
    created_by                 text NOT NULL,
    updated_at                 timestamptz NOT NULL DEFAULT now(),
    updated_by                 text NOT NULL,
    UNIQUE (child_id, target_school_year),
    -- Eine Geschwisterzahl von 0 verträgt sich nicht mit „Geschwister an der
    -- Schule": beides zusammen ist ein Ausfüllfehler, kein Sonderfall.
    -- Name bewusst nicht "applications_sibling_count_check": den vergibt
    -- Postgres bereits automatisch für den Spalten-CHECK an sibling_count, und
    -- zwei Constraints desselben Namens gibt es nicht.
    CONSTRAINT applications_siblings_at_school_count_check
        CHECK (NOT siblings_at_school OR coalesce(sibling_count, 1) > 0),
    -- Eine Rücksprache-Erlaubnis ohne Kindergarten hat keinen Adressaten.
    CONSTRAINT applications_kindergarten_consent_requires_kindergarten_check
        CHECK (kindergarten_consent_at IS NULL OR kindergarten_id IS NOT NULL),
    -- Ein Ende ohne Anfang ist kein Zeitraum, eines davor erst recht nicht.
    CONSTRAINT applications_trial_attendance_period_check
        CHECK (trial_attendance_ends_on IS NULL
               OR (trial_attendance_starts_on IS NOT NULL
                   AND trial_attendance_ends_on >= trial_attendance_starts_on)),
    -- Bestätigt werden kann nur, was gefragt wurde — dieselbe Bauform wie
    -- consents_revoked_after_granted_check.
    CONSTRAINT applications_waitlist_confirmation_requires_query_check
        CHECK (waitlist_interest_confirmed_at IS NULL
               OR (waitlist_interest_asked_at IS NOT NULL
                   AND waitlist_interest_confirmed_at >= waitlist_interest_asked_at)),
    -- Bindet school_branch_id an die Zielklassenstufe …
