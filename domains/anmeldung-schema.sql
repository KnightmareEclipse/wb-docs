-- Schulvertrag und Hortvertrag
-- ---------------------------------------------------------------------------

-- Der Vertragsvorgang beginnt mit der Zusage und endet mit der Bestätigungsmail.
-- Eigene Zeile und keine Spalten an der Bewerbung: er hat einen eigenen
-- Lebenslauf mit vier Stationen, von denen drei nach dem Absenden der Eltern
-- liegen, und die meisten Bewerbungen erreichen ihn nie.
--
-- Die vier Zeitpunkte sind bewusst Zeitpunkte und kein Statusfeld: sie treten
-- immer in dieser Reihenfolge ein, und „wann war das" ist die Frage, die im
-- Nachhinein gestellt wird (domains/anmeldung.md).
--
-- BEZUG IST ENTWEDER EINE BEWERBUNG ODER EIN KIND, getragen vom Fremdschlüssel
-- statt von einem Typ-Feld daneben, wie bei documents und payments. Er trägt
-- damit zugleich die Vertragsart: BEWERBUNG heißt Schulvertrag, KIND heißt
-- Hortvertrag.
--
-- DER HORTVERTRAG IST IMMER EIN EIGENER VORGANG — für interne Kinder wie für
-- externe, und dadurch derselbe Ablauf für beide. Drei Gründe, jeder allein
-- tragend:
--   * Er entsteht später. Am Anmeldetag steht der Betreuungsbedarf regelmäßig
--     noch nicht fest; erhoben wird dort nur applications.interested_in_care.
--     An den Schulvertrag gehängt fände ein im Mai nachgereichter Hortvertrag
--     dessen vier Zeitpunkte längst gesetzt — weder eigene Frist noch eigene
--     Prüfung durch das Sekretariat noch eigene Freigabe.
--   * Er wird im laufenden Schuljahr geändert und gekündigt, während der
--     Schulvertrag steht: Modul-Anpassungen im September, zum Halbjahr und bei
--     Stundenplanänderungen (prozesse.md Abschnitt 8).
--   * Der Hort nimmt Kinder auf, die weder Grund- noch Realschüler sind
--     (prozesse.md Abschnitt 8) — für sie gibt es gar keine Bewerbung.
-- Auch die eigene Bestätigung des Horts (Anschreiben + Welcome-Brief,
-- prozesse.md Abschnitt 5.2) braucht deshalb ihren eigenen confirmation_sent_at
-- und nicht den der Aufnahmebestätigung.
--
-- WER PRÜFT UND WER GIBT FREI, hängt an der Vertragsart und ist deshalb keine
-- Eigenschaft dieser Tabelle — die beiden Spalten sind nach der Handlung
-- benannt, nicht nach der Stelle:
--   * Schulvertrag: die Verwaltung prüft auf Vollständigkeit, die Schulleitung
--     des jeweiligen Zweigs gibt frei und zeichnet gegen (prozesse.md
--     Abschnitt 7.1).
--   * Hortvertrag: der Vorgang läuft vollständig über den Hort — der Hort prüft,
--     die HORTLEITUNG gibt frei und zeichnet gegen (prozesse.md Abschnitt 8:
--     „Unterschriften von Mutter, Vater und Hortleitung"). Die Schulleitung ist
--     hier gar nicht zuständig: sie ist je Zweig benannt (glossar.md), und ein
--     externes Hortkind hat keinen.
-- Beide Male sind es zwei verschiedene Personen — die Freigabe ist die
-- Zweitprüfung, und genau deshalb braucht das Aufsetzen keine eigene Rolle
-- (domains/anmeldung.md).
--
-- MEHRERE VERTRÄGE ÜBER DIE ZEIT SIND ZULÄSSIG, je Bewerbung wie je Kind —
-- deshalb steht auf keiner der beiden Bezugsspalten ein tabellenweites UNIQUE.
-- Zwei reale Anlässe: ein Kind schließt über die Jahre mehrere Hortverträge,
-- und ein bereits gegengezeichneter Schulvertrag muss neu aufgesetzt werden,
-- wenn nach der Freigabe auffällt, dass wesentliche Angaben fehlen (real
-- vorgekommen). Der alte Vorgang bleibt dabei stehen: er ist der Beleg, wie
-- damals entschieden wurde, und seine vier Zeitpunkte werden nicht rückdatiert.
--
-- ES GILT DER VERTRAG MIT DEM JÜNGSTEN confirmation_sent_at — abgeleitet und
-- deshalb ohne „ist aktuell"-Kennzeichen, das ein zweiter Ort für dieselbe
-- Tatsache wäre (rules.md Abschnitt 1). Ein noch laufender Neuvorgang ändert
-- damit nichts, solange er nicht abgeschlossen ist: bis dahin bleibt der zuletzt
-- bestätigte der gültige, und genau das ist die richtige Aussage.
--
-- Was bleibt, ist die Sperre gegen den Versehensfall: HÖCHSTENS EIN OFFENER
-- Vorgang je Bewerbung und je Kind (partielle Unique-Indizes unten). Zwei
-- gleichzeitig laufende Vertragsstrecken zum selben Vorgang wären keine
-- Historie, sondern ein Fehler — die Eltern bekämen zwei Links und niemand
-- wüsste, welcher zählt. Referenzmuster wie
-- care_module_bookings_one_open_per_child_and_module.
CREATE TABLE contracts (
    contract_id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    application_id        uuid REFERENCES applications(application_id) ON DELETE RESTRICT,
    child_id              uuid REFERENCES children(child_id) ON DELETE RESTRICT,
    -- Frist für die Eltern, real 14 Tage ab Versand. Als Datum und nicht als
    -- Dauer, weil die Verwaltung sie im Einzelfall verlängert.
    deadline_on            date NOT NULL,
    -- Die beiden Spalten sind nach der HANDLUNG benannt und nicht nach der
    -- Stelle, weil die Stelle von der Vertragsart abhängt (Begründung im
    -- Tabellenkopf, „Wer prüft und wer gibt frei"): beim Schulvertrag prüft die
    -- Verwaltung und die Schulleitung gibt frei, beim Hortvertrag prüft der Hort
    -- und die Hortleitung gibt frei. Ein Name wie „headmaster_released_at" wäre
    -- für die Hälfte der Zeilen schlicht falsch — die Schulleitung ist je Zweig
    -- zuständig (glossar.md), und ein externes Hortkind hat keinen.
    completeness_checked_at timestamptz,
    released_at            timestamptz,
    confirmation_sent_at   timestamptz,
    created_at             timestamptz NOT NULL DEFAULT now(),
    created_by             text NOT NULL,
    updated_at             timestamptz NOT NULL DEFAULT now(),
    updated_by             text NOT NULL,
    -- Die Reihenfolge ist Teil des Verfahrens: erst prüft die führende Stelle
    -- auf Vollständigkeit, dann gibt die zuständige Leitung frei, dann geht die
    -- Bestätigung raus. Eine Bestätigungsmail vor der Freigabe wäre genau der
    -- Fehler, der an dieser Schule niemandem auffiele.
    -- Geprüft wird beides: dass der frühere Schritt überhaupt stattgefunden hat
    -- UND dass er früher liegt. Ohne den Zeitvergleich ließe sich
    -- completeness_checked_at nachträglich hinter die Freigabe schieben, und die
    -- Zeile dokumentierte eine Prüfung, die nach der Freigabe stattfand — genau
    -- die Aussage, die diese vier Zeitpunkte tragen sollen. Gleiche Bauform wie
    -- consents_revoked_after_granted_check.
    CONSTRAINT contracts_release_after_check_check
        CHECK (released_at IS NULL
               OR (completeness_checked_at IS NOT NULL
                   AND released_at >= completeness_checked_at)),
    CONSTRAINT contracts_confirmation_after_release_check
        CHECK (confirmation_sent_at IS NULL
               OR (released_at IS NOT NULL
                   AND confirmation_sent_at >= released_at)),
    CONSTRAINT contracts_exactly_one_subject_check
        CHECK ((application_id IS NOT NULL)::int + (child_id IS NOT NULL)::int = 1)
);
CREATE INDEX ON contracts (child_id);
CREATE INDEX ON contracts (application_id);
-- Höchstens ein OFFENER Vorgang je Bezug (Kopfkommentar): abgeschlossene
-- Verträge sammeln sich als Historie, laufende darf es nur einen geben. Je
-- Bezugsspalte ein eigener partieller Index; Zeilen der jeweils anderen Art
-- tragen dort NULL und kollidieren nicht.
CREATE UNIQUE INDEX contracts_one_open_per_application
    ON contracts (application_id) WHERE confirmation_sent_at IS NULL;
CREATE UNIQUE INDEX contracts_one_open_per_child
    ON contracts (child_id) WHERE confirmation_sent_at IS NULL;

-- Antwort je Erziehungsberechtigtem. Eigene Zeilen und kein Feld am Vertrag,
-- weil Mutter und Vater je einen eigenen persönlichen Link bekommen und
-- UNTERSCHIEDLICH antworten können — sagt einer ja und der andere nein, wird das
-- Sekretariat benachrichtigt und klärt telefonisch (prozesse.md Abschnitt 7.1).
-- Genau dieser Konflikt ist an einem einzelnen Vertragsfeld nicht darstellbar.
--
-- Die Stammdatenbestätigung steht daneben: jeder bestätigt seine EIGENEN Daten,
-- die des Kindes bestätigen beide — deshalb zwei Zeitpunkte je Zeile und nicht
-- einer.
--
-- person_id ist schemaseitig eine beliebige persons-Zeile und NICHT auf die
-- Sorgeberechtigten des betroffenen Kindes eingeschränkt. Das ist eine Lücke mit
-- Ansage, keine Auslassung: die Bedingung führt über contract → application →
-- child → family → family_guardians und ist damit weder als CHECK noch als
-- Fremdschlüssel ausdrückbar, sondern nur als Trigger — und Trigger für
-- tabellenübergreifende Bedingungen lehnt dieses Projekt an jeder vergleichbaren
-- Stelle ab (Freikauf-Frist in domains/putzdienst-schema.sql, slot_date im
-- Zyklus, phone_numbers.is_primary). Die Bindung entsteht stattdessen dort, wo
-- der persönliche Vertragslink erzeugt wird: er geht ausschließlich an die
-- Erziehungsberechtigten der Familie des Kindes (idea/04-identitaet-zugriff.md).
-- Genannt wird es hier, weil das die rechtlich gewichtigste Tabelle der Domäne
-- ist und die Lücke sonst wie ein Versehen aussähe.
CREATE TABLE contract_responses (
    contract_id             uuid NOT NULL REFERENCES contracts(contract_id) ON DELETE CASCADE,
    person_id               uuid NOT NULL REFERENCES persons(person_id) ON DELETE RESTRICT,
    accepted                boolean,
    responded_at            timestamptz,
    own_data_confirmed_at   timestamptz,
    child_data_confirmed_at timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    created_by              text NOT NULL,
    updated_at              timestamptz NOT NULL DEFAULT now(),
    updated_by              text NOT NULL,
    PRIMARY KEY (contract_id, person_id),
    -- Eine Antwort ohne Zeitpunkt ist keine, und ein Zeitpunkt ohne Antwort
    -- ebenso wenig.
    CONSTRAINT contract_responses_answer_complete_check
        CHECK ((accepted IS NULL) = (responded_at IS NULL))
);
CREATE INDEX ON contract_responses (person_id);

