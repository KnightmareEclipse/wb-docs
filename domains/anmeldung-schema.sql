-- Katalog der buchbaren Module: Frühbetreuung, vier Nachmittagsvarianten, Hort
-- nach Mittagschule (prozesse.md Abschnitt 8). Werteliste, weil die Schule
-- Module streicht und ergänzt, ohne dass eine Migration nötig sein darf.
--
-- school_branch_id nullable: „Hort nach Mittagschule" gilt nur für die
-- Realschule, alle übrigen für beide Zweige. NULL heißt also „ohne
-- Einschränkung" und nicht „unbekannt".
--
-- Dass ein Kind nur ein Modul seines eigenen Zweigs bucht, erzwingt das Schema
-- NICHT: der Zweig des Kindes führt über children.class_id → classes und wäre
-- nur als Trigger prüfbar. Dieselbe dokumentierte Lücke wie bei
-- contract_responses.person_id unten, program_bookings.child_id
-- (domains/ferien-schema.sql) und class_parent_representatives.guardian_id
-- (domains/klassenorganisation-schema.sql) — die Bindung liegt in der
-- Buchungsstrecke, die nur die für dieses Kind gültigen Module anbietet.
CREATE TABLE care_modules (
    care_module_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label             text NOT NULL UNIQUE CHECK (label <> ''),
    school_branch_id  integer REFERENCES school_branches(school_branch_id) ON DELETE RESTRICT,
    -- Zeiten als Text und nicht als time-Spalten: der reale Katalog beginnt
    -- überwiegend bei „Schulende" und nicht zu einer Uhrzeit, und diese Angabe
    -- steht im Formular, wird aber von keiner Abfrage ausgewertet.
    time_description  text NOT NULL CHECK (time_description <> ''),
    -- Die Hausaufgabenbetreuung ist Bestandteil des MODULS, kein eigenes
    -- Interesse- oder Buchungsfeld an Bewerbung oder Buchung: real enthalten
    -- die Nachmittagsbetreuungen 2–4 sie, Modul 1 (nur bis 13:00) nicht
    -- (prozesse.md Abschnitt 8). Wer sie bekommt, entscheidet damit allein die
    -- Modulwahl — ein Feld daneben wäre ein zweiter Ort für dieselbe Tatsache.
    includes_homework boolean NOT NULL DEFAULT false,
    -- Dieselbe Bauform für das Mittagessen: der Betreuungsvertrag berechnet es
    -- „für alle Schüler, die länger als 13 Uhr betreut werden" — ob ein Modul
    -- das auslöst, ist eine Eigenschaft des Moduls und keine eigene Buchung.
    -- Aus time_description (Freitext) ist die 13-Uhr-Grenze nicht maschinell
    -- ablesbar, deshalb ein eigenes Kennzeichen, gepflegt von der Verwaltung.
    -- Das Katalogmodul „Mittagessen" (RS-Mensa-Abo, domains/mensa.md) trägt es
    -- trivialerweise auch — „isst mit" ist damit EIN Prädikat über EINE
    -- Tabelle: aktive Buchung eines includes_lunch-Moduls am jeweiligen
    -- Wochentag. Abnehmer sind die Küchen-Tagesliste und der Abrechnungshinweis
    -- an die Buchhaltung („Zuzüglich Mittagessen"); die Abrechnung selbst
    -- bleibt bei Optigem (domains/grenzkarte.md, Q3).
    includes_lunch    boolean NOT NULL DEFAULT false,
    sort_order        smallint NOT NULL UNIQUE,
    created_at        timestamptz NOT NULL DEFAULT now(),
    created_by        text NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    updated_by        text NOT NULL
);

-- Gebuchtes Modul für ein Kind, mit eigenem Gültigkeitszeitraum.
--
-- Hängt am KIND und nicht am Vertragsvorgang: der Hort nimmt auch Kinder auf,
-- die weder Grund- noch Realschüler sind (prozesse.md Abschnitt 8) — für sie
-- gibt es keine Bewerbung, aber eine Buchung. contract_id sagt nur, aus welchem
-- Vorgang die Buchung entstanden ist: bei Betreuungsmodulen der Hortvertrag des
-- Kindes (Begründung an contracts, gilt für interne wie externe Kinder), beim
-- Mensa-Abo gar keiner — deshalb nullable.
--
-- valid_from/valid_until tragen Laufzeit, Kündigung und Angebotsende in einem:
-- der reale Betreuungsvertrag läuft ein Schuljahr (01.08.–31.07.) und
-- verlängert sich stillschweigend, kündbar mit Monatsfrist (prozesse.md
-- Abschnitt 8) — valid_until bleibt also NULL, solange nichts endet, und wird
-- bei Kündigung oder Angebotsende gesetzt (das Hortangebot endet mit
-- Klasse 5). Als Datum und nicht als Regel im Code, weil die Schule Fristen
-- und Grenzen verschiebt.
--
-- Dieselben zwei Tabellen tragen auch das MENSA-Wochentags-Abo der Realschule:
-- dessen Anmeldeformular ist dieselbe Buchungsform (Wochentage ankreuzen,
-- Monatsbeitrag, Schuljahreslaufzeit, Kündigung zum Halbjahr) — im Katalog
-- steht dafür die Zeile „Mittagessen" mit includes_lunch, eine eigene
-- Buchungstabelle gäbe es nur dem Namen nach (domains/mensa.md).
CREATE TABLE care_module_bookings (
    care_module_booking_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    child_id               uuid NOT NULL REFERENCES children(child_id) ON DELETE RESTRICT,
    care_module_id         integer NOT NULL REFERENCES care_modules(care_module_id) ON DELETE RESTRICT,
    contract_id            uuid REFERENCES contracts(contract_id) ON DELETE RESTRICT,
    valid_from             date NOT NULL,
    valid_until            date,
    created_at             timestamptz NOT NULL DEFAULT now(),
    created_by             text NOT NULL,
    updated_at             timestamptz NOT NULL DEFAULT now(),
    updated_by             text NOT NULL,
    UNIQUE (child_id, care_module_id, valid_from),
    CONSTRAINT care_module_bookings_period_check
        CHECK (valid_until IS NULL OR valid_until >= valid_from)
);
CREATE INDEX ON care_module_bookings (child_id);
-- Höchstens EINE offene Buchung je Kind und Modul. Das UNIQUE oben schließt
-- valid_from ein und lässt deshalb zwei Zeilen desselben Moduls mit
-- verschiedenem Beginn und beide ohne Ende zu — genau die Form, in der eine
-- Modul-Anpassung real entsteht: alte Buchung beenden, neue anlegen
-- (prozesse.md Abschnitt 8, im September kostenfrei, zum Halbjahr gegen
-- Gebühr). Wird das valid_until der alten dabei vergessen, sind beide „aktiv",
-- und „isst am Wochentag X mit" (domains/mensa.md) zählt dasselbe Kind zweimal:
-- die Küche kocht eine Portion zu viel und der Abrechnungshinweis geht doppelt
-- an die Buchhaltung. Beides fällt niemandem auf, weil jede Zeile für sich
-- gültig aussieht.
--
-- Der Index erzwingt damit die richtige Reihenfolge (erst schließen, dann neu
-- anlegen) und trägt zugleich die Zusage aus domains/anmeldung.md, „welcher
-- Vertrag gilt, sagt die Laufzeit der Buchung".
--
-- Partieller Index statt EXCLUDE über daterange: volle Überlappungsfreiheit
-- bräuchte btree_gist für die beiden Gleichheitsspalten (uuid, integer) und
-- damit eine Extension — für den realen Fehlerfall (die alte Zeile nicht
-- geschlossen) genügt die offene Buchung. Referenzmuster wie
-- phone_numbers_one_primary_per_person in Stammdaten und
-- program_bookings_one_active_per_child_and_day in der Ferien-Domäne.
CREATE UNIQUE INDEX care_module_bookings_one_open_per_child_and_module
    ON care_module_bookings (child_id, care_module_id) WHERE valid_until IS NULL;

-- Die Buchungseinheit ist Modul × Wochentag, nicht das Modul allein: je Modul
-- werden die einzelnen Tage gewählt (prozesse.md Abschnitt 8). Deshalb eine
-- eigene Zeile je Tag und keine sieben Boolean-Spalten — ein Wochentag mehr oder
-- weniger ist damit ein Datensatz.
--
-- MIT Audit-Spalten, obwohl die Buchung darüber sie ohnehin trägt: der Wochentag
-- IST hier die Buchungseinheit und keine Verfeinerung. Ein entfernter Mittwoch
-- ändert Leistung und Rechnung, und die Audit-Spalten der Buchungszeile bleiben
-- dabei unberührt — die Änderung wäre spurlos.
CREATE TABLE care_module_booking_days (
    care_module_booking_id uuid NOT NULL REFERENCES care_module_bookings(care_module_booking_id) ON DELETE CASCADE,
    -- ISO-8601: 1 = Montag … 5 = Freitag. Betreuung am Wochenende gibt es nicht,
    -- und ein Tippfehler „7" wäre sonst eine stille Buchung ins Leere.
    weekday                smallint NOT NULL CHECK (weekday BETWEEN 1 AND 5),
    created_at             timestamptz NOT NULL DEFAULT now(),
    created_by             text NOT NULL,
    updated_at             timestamptz NOT NULL DEFAULT now(),
    updated_by             text NOT NULL,
    PRIMARY KEY (care_module_booking_id, weekday)
);

